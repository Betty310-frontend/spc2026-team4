def resolve_category(text: str) -> str | None:
    """자연어 텍스트 → TARGET 업종명. 매칭 없으면 None."""
    key = text.strip()
    if key in TARGET:
        return key
    return _ALIASES.get(key)


def resolve_to_map_key(text: str) -> str:
    """자연어 텍스트 → category_map._MAP 키. 매칭 없으면 원문 반환."""
    target = resolve_category(text)
    if target is None:
        return text.strip()
    return _TARGET_TO_MAP_KEY.get(target, text.strip())
